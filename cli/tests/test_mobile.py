class TestScanCommand(EnvironmentTestCase):
    def test_skips_without_docker(self):
        repo = self.home / "repo"
        android_app(repo)
        write(repo, ".tdxguard.yml", "project: shop\nmobile:\n  - source: android\n")
        summary = {"rows": [], "errors": []}
        with patch("tdxguard.commands.mobsf_scan.scan") as scan:
            from tdxguard import commands
            from tdxguard.ui import UI

            errors = commands._scan_mobile(UI(), config.load(repo), repo, repo / "out", summary, lambda: False)
        scan.assert_not_called()
        self.assertEqual([], errors)
        self.assertIn("MobSF runs in Docker, which is not available here", summary["warnings"][0])

    def test_rows_join_the_summary(self):
        repo = self.home / "repo"
        android_app(repo)
        write(repo, ".tdxguard.yml", "project: shop\nmobile:\n  - app: app.apk\n  - source: android\n")
        summary = {"rows": []}
        rows = [
            {"label": "MobSF (app: app.apk)", "report": "mobsf-app-apk.json", "findings": 3, "severe": 1},
            {"label": "MobSF (source: android:.)", "report": "mobsf-android.json", "error": "boom"},
        ]
        with patch("tdxguard.commands.mobsf_scan.scan", return_value=rows) as scan:
            from tdxguard import commands
            from tdxguard.ui import UI

            errors = commands._scan_mobile(UI(), config.load(repo), repo, repo / "out", summary, lambda: True)
        self.assertEqual((["app.apk"], ["android:."]), scan.call_args[0][2:4])
        self.assertEqual(["MobSF: boom"], errors)
        self.assertEqual([{"label": "MobSF (app: app.apk)", "findings": 3, "severe": 1}], summary["rows"])

    def test_skip_mobile_is_accepted(self):
        from tdxguard import __main__ as entry
        from tdxguard import commands

        args = entry.build_parser().parse_args(["scan", "--skip", "mobile", "--skip", "trivy"])
        self.assertEqual(["mobile", "trivy"], commands.resolve_skips(args))


