class TestMobSFHelper(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name) / "repo"
        self.out = Path(self.tmp.name) / "out"
        write(self.root, "app/build/outputs/apk/release/app-release.apk", "PK")
        android_app(self.root)
        write(self.root, "app/build/intermediates/x.class", "")
        write(self.root, ".gradle/cache.bin", "")

    def test_resolve(self):
        app = mobsf_scan.resolve_app(self.root, "app/build/outputs/apk/release/*.apk")
        self.assertEqual("mobsf-app-build-outputs-apk-release-apk.json", app.report_name)
        source = mobsf_scan.resolve_source(self.root, "android")
        self.assertEqual("mobsf-android.json", source.report_name)
        self.assertEqual("android", mobsf_scan.source_layout(self.root))
        for argument, fragment in (
            ("app/*.ipa", "no such file"),
            ("../x.apk", "relative to the repository root"),
            ("app/build.gradle.kts", "MobSF analyses"),
        ):
            with self.subTest(argument=argument), self.assertRaises(mobsf_scan.MobSFError) as cm:
                mobsf_scan.resolve_app(self.root, argument)
            self.assertIn(fragment, str(cm.exception))
        write(self.root, "app/build/outputs/apk/debug/app-debug.apk", "PK")
        with self.assertRaises(mobsf_scan.MobSFError) as cm:
            mobsf_scan.resolve_app(self.root, "app/build/outputs/apk/*/*.apk")
        self.assertIn("matches 2 files", str(cm.exception))

    def test_source_layouts(self):
        with self.assertRaises(mobsf_scan.MobSFError) as cm:
            mobsf_scan.resolve_source(self.root, "ios")
        self.assertIn("holds an Android project as well", str(cm.exception))
        # Modules without an app/ module: MobSF does not take the zip
        other = Path(self.tmp.name) / "modules"
        write(other, "settings.gradle", "")
        write(other, "blocker/src/main/AndroidManifest.xml", "<manifest/>")
        with self.assertRaises(mobsf_scan.MobSFError) as cm:
            mobsf_scan.resolve_source(other, "android")
        self.assertIn("Android Studio layout", str(cm.exception))
        ios = Path(self.tmp.name) / "ios"
        ios_app(ios, "App/")
        self.assertEqual("ios", mobsf_scan.source_layout(ios))
        self.assertEqual("mobsf-ios.json", mobsf_scan.resolve_source(ios, "ios").report_name)

    def test_zip_leaves_out_build_output(self):
        destination = Path(self.tmp.name) / "source.zip"
        mobsf_scan.zip_source(self.root, destination)
        names = zipfile.ZipFile(destination).namelist()
        self.assertIn("app/src/main/AndroidManifest.xml", names)
        self.assertFalse([n for n in names if n.startswith(("app/build/", ".gradle/"))])

    def test_scan_isolates_the_container_and_writes_the_reports(self):
        docker = FakeDocker(REPORT, networks=("bridge", "none"))
        with patch("time.sleep"):
            rows = mobsf_scan.scan(
                self.root,
                self.out,
                ["app/build/outputs/apk/release/*.apk"],
                ["android"],
                run=docker,
                log=lambda m: None,
            )
        self.assertEqual([None, None], [row.get("error") for row in rows])
        self.assertEqual((3, 1), (rows[0]["findings"], rows[0]["severe"]))
        self.assertEqual(
            ["mobsf-android.json", "mobsf-app-build-outputs-apk-release-apk.json"],
            sorted(p.name for p in self.out.iterdir()),
        )
        commands = [" ".join(call[:3]) for call in docker.calls]
        disconnect = commands.index("docker network disconnect")
        first_copy = next(i for i, c in enumerate(commands) if c.startswith("docker cp"))
        self.assertLess(disconnect, first_copy, "the network is cut before the app is copied in")
        self.assertEqual(["docker", "network", "disconnect", "-f", "bridge"], docker.calls[disconnect][:5])
        self.assertEqual(1, commands.count("docker network disconnect"), "the none network is left alone")
        run = docker.calls[0]
        self.assertIn("MOBSF_DOMAIN_MALWARE_SCAN=0", run)
        self.assertNotIn("-p", run, "no port is published")
        self.assertEqual("docker rm -f", commands[-1])
        # MobSF does not run as root: the copied app is made readable whatever its mode
        copy = next(i for i, call in enumerate(docker.calls) if call[:2] == ["docker", "cp"])
        self.assertEqual(["docker", "exec", "-u", "0"], docker.calls[copy + 1][:4])
        self.assertEqual(["chmod", "a+r"], docker.calls[copy + 1][5:7])

