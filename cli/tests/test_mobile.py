def write(root: Path, relative: str, text: str = "") -> None:
    path = root / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


def android_app(root: Path, prefix: str = "") -> None:
    write(root, f"{prefix}settings.gradle.kts", 'include(":app", ":core:network")\n')
    write(root, f"{prefix}build.gradle.kts", 'plugins { id("com.android.application") version "8.5.0" apply false }\n')
    write(root, f"{prefix}app/build.gradle.kts", 'plugins { id("com.android.application") }\nandroid { }\n')
    write(root, f"{prefix}core/network/build.gradle.kts", 'plugins { id("com.android.library") }\n')
    write(root, f"{prefix}gradle/libs.versions.toml", '[versions]\nokhttp = "4.12.0"\n')
    write(root, f"{prefix}app/src/main/AndroidManifest.xml", "<manifest/>\n")
    write(root, f"{prefix}app/src/main/kotlin/com/example/demo/MainActivity.kt", "class MainActivity\n")


def ios_app(root: Path, prefix: str = "") -> None:
    write(root, f"{prefix}Demo.xcodeproj/project.pbxproj", "// !$*UTF8*$!\n")
    write(root, f"{prefix}Demo/AppDelegate.swift", "import UIKit\n")
    write(root, f"{prefix}Podfile", "platform :ios, '15.0'\npod 'Alamofire'\n")


